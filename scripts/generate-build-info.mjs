import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const packageJson = JSON.parse(readFileSync(resolve("package.json"), "utf8"));

function git(...args) {
  try {
    return execFileSync(
      "git",
      ["-c", `safe.directory=${process.cwd().replaceAll("\\", "/")}`, ...args],
      {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      },
    ).trim();
  } catch {
    return "";
  }
}

const fullCommit = process.env.GITHUB_SHA || git("rev-parse", "HEAD");
const commit = fullCommit ? fullCommit.slice(0, 8) : "uncommitted";
const ref = process.env.GITHUB_REF_NAME || "";
const releaseTag = /^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(ref)
  ? ref.slice(1)
  : "";
const version =
  process.env.APP_VERSION ||
  releaseTag ||
  `${packageJson.version}-dev+${commit}`;
const channel = releaseTag ? "release" : "development";

const output = `// Generated by scripts/generate-build-info.mjs. Do not edit.
export const BUILD_INFO = {
  version: ${JSON.stringify(version)},
  commit: ${JSON.stringify(commit)},
  channel: ${JSON.stringify(channel)},
  builtAt: ${JSON.stringify(new Date().toISOString())},
} as const;
`;

writeFileSync(resolve("src/shared/build-info.generated.ts"), output);
console.log(`Build identity: ${version}`);
